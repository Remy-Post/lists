test('parseDate (whole-string date field)', () => {
  eq(parseDate('tomorrow', NOW), '2026-11-05')
  eq(parseDate('  Fri ', NOW), '2026-11-06')
  eq(parseDate('on fri', NOW), '2026-11-06')
  eq(parseDate('tom', NOW), '2026-11-05', 'tom works in the date field')
  eq(parseDate('aug', NOW), '2027-08-01', 'bare month = the 1st')
  eq(parseDate('May', NOW), '2027-05-01')
  eq(parseDate('yesterday', NOW), '2026-11-03')
  eq(parseDate('nov 14 2027', NOW), '2027-11-14')
  eq(parseDate('2026-02-30', NOW), null)
  eq(parseDate('someday', NOW), null)
  eq(parseDate('garbage', NOW), null)
  eq(parseDate('', NOW), null)
  eq(parseDate('tomorrow pls', NOW), null, 'must be the whole string')
})

