test('tokens carry exact offsets; title collapses whitespace', () => {
  const s = 'Call mom tomorrow !! #home @phone'
  const r = q(s)
  de(r.tokens.map(t => [t.kind, t.start, t.end]), [['when', 9, 17], ['priority', 18, 20], ['list', 21, 26], ['tag', 27, 33]])
  for (const t of r.tokens) eq(s.slice(t.start, t.end), t.text)
  const g = q('  buy   milk  in 3 days  by fri ')
  eq(g.title, 'buy milk')
  for (const t of g.tokens) eq(g.tokens.length && '  buy   milk  in 3 days  by fri '.slice(t.start, t.end), t.text)
  de(g.tokens.map(t => t.text), ['in 3 days', 'by fri'])
  const u = 'Café İstanbul trip tomorrow'
  const ut = q(u).tokens[0]
  eq(u.slice(ut.start, ut.end), 'tomorrow')
})

test('ignore spans make tokens literal', () => {
  const s = 'Call mom tomorrow !!'
  const r = q(s, NOW, { ignore: [[9, 17]] })
  eq(r.when, null); eq(r.priority, 2); eq(r.title, 'Call mom tomorrow')
  const n = q('lunch next fri', NOW, { ignore: [[6, 14]] })
  eq(n.when, null, 'inner "fri" of an ignored span is not re-parsed'); eq(n.tokens.length, 0)
  const p = q('x !! tomorrow', NOW, { ignore: [[2, 4]] })
  eq(p.priority, 0); eq(p.when, '2026-11-05'); eq(p.title, 'x !!')
  const d = q('lunch tomorrow fri', NOW, { ignore: [[6, 14]] })
  eq(d.when, '2026-11-06', 'next candidate takes over')
  const e = q('water every 3 days', NOW, { ignore: [[6, 18]] })
  eq(e.rrule, null); eq(e.when, null)
})

